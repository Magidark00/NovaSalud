-- 1. Tabla de Usuarios y Roles
CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  nombre TEXT NOT NULL,
  rol TEXT NOT NULL CHECK (rol IN ('Administrador', 'Farmacéutico', 'Cajero', 'Almacenero')),
  iniciales TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Tabla de Productos (Inventario)
CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT UNIQUE NOT NULL,
  nombre TEXT NOT NULL,
  presentacion TEXT NOT NULL,
  categoria TEXT NOT NULL,
  proveedor TEXT NOT NULL,
  precio NUMERIC(10, 2) NOT NULL CHECK (precio >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  stock_minimo INTEGER NOT NULL DEFAULT 10 CHECK (stock_minimo >= 0),
  vence TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabla de Clientes
CREATE TABLE IF NOT EXISTS clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni TEXT UNIQUE NOT NULL,
  nombre TEXT NOT NULL,
  telefono TEXT,
  email TEXT,
  direccion TEXT,
  compras INTEGER NOT NULL DEFAULT 0,
  ultima_compra TEXT,
  total_gastado NUMERIC(10, 2) NOT NULL DEFAULT 0,
  ultimas_compras_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Tabla de Ventas (Cabecera de Boletas)
CREATE TABLE IF NOT EXISTS ventas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_boleta INTEGER UNIQUE NOT NULL,
  codigo_boleta TEXT UNIQUE NOT NULL,
  cliente_id BIGINT REFERENCES clientes(id) ON DELETE SET NULL,
  cliente_nombre TEXT NOT NULL DEFAULT 'Cliente general',
  usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  metodo_pago TEXT NOT NULL,
  subtotal NUMERIC(10, 2) NOT NULL,
  igv NUMERIC(10, 2) NOT NULL,
  descuento NUMERIC(10, 2) NOT NULL DEFAULT 0,
  total NUMERIC(10, 2) NOT NULL,
  recibido NUMERIC(10, 2),
  vuelto NUMERIC(10, 2) DEFAULT 0,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Tabla de Detalle de Ventas (Líneas de Boleta)
CREATE TABLE IF NOT EXISTS detalle_ventas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id BIGINT NOT NULL REFERENCES ventas(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES productos(id) ON DELETE SET NULL,
  producto_nombre TEXT NOT NULL,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(10, 2) NOT NULL,
  importe NUMERIC(10, 2) NOT NULL
);

-- 6. Tabla de Resumen de Ventas Semanales (Dashboard)
CREATE TABLE IF NOT EXISTS ventas_semanales_resumen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dia TEXT UNIQUE NOT NULL,
  orden INTEGER NOT NULL,
  ventas NUMERIC(10, 2) NOT NULL DEFAULT 0
);

-- 7. Tabla de Órdenes de Reposición
CREATE TABLE IF NOT EXISTS ordenes_reposicion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT UNIQUE NOT NULL,
  proveedor TEXT NOT NULL,
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'recibida', 'cancelada')),
  usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  observaciones TEXT
);

-- 8. Tabla de Detalle de Órdenes de Reposición
CREATE TABLE IF NOT EXISTS detalle_reposicion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id BIGINT NOT NULL REFERENCES ordenes_reposicion(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES productos(id) ON DELETE SET NULL,
  producto_nombre TEXT NOT NULL,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0)
);

